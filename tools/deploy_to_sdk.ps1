<#
.SYNOPSIS
    把 app/ 下的模块化源码部署进 ML307A OpenCPU SDK 工程（custom/applaction/）。

.DESCRIPTION
    - app/ 是工程的"唯一源码来源"（source of truth），可直接用 PC 上的 gcc 做单元测试。
    - 本脚本把 app/inc/*.h 与 app/src/*.c 复制进 SDK 的 custom/applaction/，
      并重新生成 custom/custom.mk（列出全部 .c 文件与 include 路径）。
    - SDK 原始 main.c 会在首次部署时备份为 main.c.sdk_orig，避免误覆盖丢失。
    - SDK 自带的 app.c 仍然参与编译：它提供 osThreadCreat / osTimerCreat / osDelayMs
      三个包装函数，custom/drv 下的串口驱动会引用到。

.EXAMPLE
    pwsh -File tools/deploy_to_sdk.ps1
    pwsh -File tools/deploy_to_sdk.ps1 -SdkDir "D:\sdk\ML307A_OpenCPU_Standard_1.4.2"
#>
[CmdletBinding()]
param(
    [string]$SdkDir = (Join-Path $PSScriptRoot '..\sdk\ML307A_OpenCPU_Standard_1.4.2'),
    [string]$AppDir = (Join-Path $PSScriptRoot '..\app')
)

$ErrorActionPreference = 'Stop'

$SdkDir = (Resolve-Path $SdkDir).Path
$AppDir = (Resolve-Path $AppDir).Path
$dst    = Join-Path $SdkDir 'custom\applaction'

if (-not (Test-Path $dst)) {
    throw "目标目录不存在，SdkDir 是否正确？ $dst"
}

Write-Host "== 部署应用源码到 SDK ==" -ForegroundColor Cyan
Write-Host "  源: $AppDir"
Write-Host "  目标: $dst"

# 1) 首次部署时备份 SDK 原始 main.c
$sdkMain = Join-Path $dst 'main.c'
$bakMain = Join-Path $dst 'main.c.sdk_orig'
if ((Test-Path $sdkMain) -and -not (Test-Path $bakMain)) {
    Copy-Item $sdkMain $bakMain
    Write-Host "  已备份 SDK 原始 main.c -> main.c.sdk_orig" -ForegroundColor Yellow
}

# 2) 复制头文件与源文件
$headers = Get-ChildItem (Join-Path $AppDir 'inc') -Filter *.h
$sources = Get-ChildItem (Join-Path $AppDir 'src') -Filter *.c
foreach ($f in $headers) { Copy-Item $f.FullName $dst -Force }
foreach ($f in $sources) { Copy-Item $f.FullName $dst -Force }

Write-Host ("  复制头文件 {0} 个，源文件 {1} 个" -f $headers.Count, $sources.Count)

# 3) 生成 custom.mk
$names = $sources | ForEach-Object { $_.Name } | Sort-Object
$mk = New-Object System.Collections.Generic.List[string]
$mk.Add('include tools/scripts/config.mk')
$mk.Add('')
# 注释用英文，避免以 ASCII 编码写出时中文变成问号（make 会忽略注释，但影响可读性）
$mk.Add('# Auto-generated by tools/deploy_to_sdk.ps1 -- DO NOT EDIT BY HAND.')
$mk.Add('# To add/remove sources, change app/src and re-run the script.')
$mk.Add('')
$mk.Add('CUSTOM_DIR := custom')
$mk.Add('APPLACTION_DIR := custom/applaction')
$mk.Add('')
$mk.Add('# User application sources')
$mk.Add('OC_FILES += $(APPLACTION_DIR)/app.c   # SDK-provided wrappers: osThreadCreat/osDelayMs')
foreach ($n in $names) {
    $pad = ' ' * [Math]::Max(1, 28 - $n.Length)
    $mk.Add("OC_FILES += `$(APPLACTION_DIR)/$n$pad# app module")
}
$mk.Add('')
$mk.Add("INC += -I'`$(APPLACTION_DIR)'")
$mk.Add('')
$mk.Add('ifeq ($(strip $(DEMO_SUPPORT)),n)')
$mk.Add('include $(CUSTOM_DIR)/drv/drv.mk')
$mk.Add('endif')
$mk.Add('')

$mkPath = Join-Path $SdkDir 'custom\custom.mk'
Set-Content -Path $mkPath -Value ($mk -join "`r`n") -Encoding ASCII

Write-Host "  已生成 custom/custom.mk" -ForegroundColor Green
Write-Host ""
Write-Host "部署完成。下一步编译：" -ForegroundColor Cyan
Write-Host "  pwsh -File tools/build_firmware.ps1"
